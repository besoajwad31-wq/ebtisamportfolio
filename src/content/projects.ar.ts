import { projects, type Project, type ProjectImage } from "./projects";

/**
 * Arabic translations of the project case studies in `projects.ts`.
 * Structure (slug, number, images, illustration) is taken from the English
 * entry so both languages always show the same projects and files; only the
 * wording below is translated.
 */

function base(slug: string): Project {
  const project = projects.find((p) => p.slug === slug);
  if (!project) throw new Error(`Missing English project "${slug}"`);
  return project;
}

/** Re-uses the English image files in order, with Arabic alt text and captions. */
function localizeImages(images: ProjectImage[], texts: { alt: string; caption: string }[]): ProjectImage[] {
  return texts.map((text, i) => ({ src: images[i]?.src ?? "", ...text }));
}

